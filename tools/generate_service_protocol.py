"""Generate only MPSC2's descriptor against installed upstream protocol descriptors.

Requires protoc on PATH; generated bindings need no compiler at runtime. Using
protobuf's descriptor builder avoids a compiler-version-specific runtime check.
"""
from pathlib import Path
import subprocess
import tempfile
from google.protobuf.descriptor_pb2 import FileDescriptorSet
from s2clientprotocol import sc2api_pb2

root = Path(__file__).resolve().parents[1]
upstream, seen = FileDescriptorSet(), set()
def add(file):
    if file.name in seen:
        return
    seen.add(file.name)
    for dep in file.dependencies:
        add(dep)
    file.CopyToProto(upstream.file.add())
add(sc2api_pb2.DESCRIPTOR)
with tempfile.TemporaryDirectory() as directory:
    path = Path(directory)
    (path / 'upstream.pb').write_bytes(upstream.SerializeToString())
    subprocess.run(['protoc', '-I', str(root / 'protocols'),
                    '--descriptor_set_in=' + str(path / 'upstream.pb'),
                    '--descriptor_set_out=' + str(path / 'mpsc2.pb'),
                    'mpsc2/v1/multiplayer.proto'], check=True)
    descriptors = FileDescriptorSet.FromString((path / 'mpsc2.pb').read_bytes())
    descriptor = next(d for d in descriptors.file if d.name == 'mpsc2/v1/multiplayer.proto')
    data = descriptor.SerializeToString()
    (root / 'src/mpsc2/service/multiplayer_pb2.py').write_text(
        '# Generated by tools/generate_service_protocol.py. DO NOT EDIT.\n'
        'from google.protobuf import descriptor_pool as _pool\n'
        'from google.protobuf.internal import builder as _builder\n'
        'from s2clientprotocol import common_pb2 as _common, sc2api_pb2 as _api\n\n'
        f'DESCRIPTOR = _pool.Default().AddSerializedFile({data!r})\n'
        '_builder.BuildMessageAndEnumDescriptors(DESCRIPTOR, globals())\n'
        '_builder.BuildTopDescriptorsAndMessages(DESCRIPTOR, __name__, globals())\n', encoding='utf-8')
